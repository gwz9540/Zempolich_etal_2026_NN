function MI_Output = runPermShuffle_spikes(spikes1, spikes2, numPerms)
% runPermShuffle Estimates modulation index percentiles using permutation
%                 shuffling to compare two sets of spike-related values.
%
%   MI_Output = runPermShuffle(spikes1, spikes2, numPerms)
%
%   INPUTS:
%       spikes1  - Cell array in which each cell contains the values for
%                  the first condition or group for a given neuron.
%       spikes2  - Cell array in which each cell contains the values for
%                  the second condition or group for a given neuron.
%                  Each cell corresponds to the same neuron as the cell
%                  at the same index in spikes1.
%       numPerms - Number of random permutations used to generate the
%                  null distribution for each neuron.
%
%   OUTPUT:
%       MI_Output - Vector containing the percentile rank of the observed
%                   modulation index for each neuron, expressed as a
%                   percentage between 0 and 100.
%                   Each value represents the position of the observed
%                   modulation index relative to its permutation-based
%                   null distribution.
%
%   METHOD:
%       For each neuron, the observed modulation index (MI) is calculated
%       from the means of the two conditions:
%
%           MI_Real = (mean1 - mean2) / (mean1 + mean2)
%
%       where:
%           mean1 - Mean of the values in the first condition.
%           mean2 - Mean of the values in the second condition.
%
%       NaN values are excluded when calculating the condition means.
%
%       A permutation-based null distribution is generated by combining
%       the values from both conditions, randomly shuffling their order,
%       and splitting the shuffled values into two groups with the same
%       sizes as the original conditions. The modulation index is
%       recalculated for each permutation:
%
%           MI_Shuffled = (m1 - m2) / (m1 + m2)
%
%       where:
%           m1 - Mean of the first shuffled group.
%           m2 - Mean of the second shuffled group.
%
%       The observed modulation index is then compared with the shuffled
%       distribution using compute_percentile. Ties are assigned half
%       weight when calculating the percentile rank.
%
%   APPLICATION:
%       This function evaluates whether the observed difference between
%       two conditions for each neuron is unusual relative to a null
%       distribution generated by randomly reallocating the pooled
%       observations between the two conditions.
%
%       Values near 0 or 100 indicate that the observed modulation index
%       lies near the lower or upper end of the null distribution,
%       respectively.
%
%
%   DEPENDENCIES:
%       compute_percentile - Calculates the percentile rank of an observed
%                            value relative to a reference distribution.
%
% Author:       Grant W. Zempolich
% Created:      2024-04-16
% Last updated: 2026-10-23

% Determine the number of neurons and initialize the output vector.
nNeurons = numel(spikes1);
MI_Output = nan(1, nNeurons);

% Set the number of permutations processed in each batch to limit memory
% usage when generating shuffled datasets.
batchSize = 1000;

% Process each neuron independently.
for i = 1:nNeurons

    % Extract the observations for the current neuron and convert them
    % into row vectors to ensure consistent concatenation and indexing.
    current1 = spikes1{i}(:)';
    current2 = spikes2{i}(:)';

    % Record the size of the first condition and combine the observations
    % from both conditions. The original group sizes are preserved during
    % permutation shuffling.
    n1 = numel(current1);
    allSpikes = [current1, current2];
    nTotal = numel(allSpikes);

    % Calculate the observed modulation index using the original data.
    % NaN values are omitted when calculating the condition means.
    mean1 = mean(current1, 'omitnan');
    mean2 = mean(current2, 'omitnan');

    MI_Real = (mean1 - mean2) / (mean1 + mean2);

    % Preallocate the null distribution to store the modulation index
    % obtained from each permutation.
    MI_Shuffled = nan(1, numPerms);

    % Generate and evaluate permutations in batches to reduce memory use.
    for firstPerm = 1:batchSize:numPerms

        % Determine the index range and number of permutations in the
        % current batch, accounting for a potentially smaller final batch.
        lastPerm = min(firstPerm + batchSize - 1, numPerms);
        nBatch = lastPerm - firstPerm + 1;

        % Generate random permutations for each column by sorting random
        % values. Each column of permIdx contains a random ordering of
        % the pooled observations for one permutation.
        [~, permIdx] = sort(rand(nTotal, nBatch), 1);

        % Apply the generated permutations to the pooled observations.
        % Each column represents one shuffled dataset.
        shuffled = allSpikes(permIdx);

        % Split each shuffled dataset into two groups using the original
        % size of the first condition. The remaining values form the
        % second condition.
        shuffled1 = shuffled(1:n1, :);
        shuffled2 = shuffled(n1+1:end, :);

        % Calculate the mean of each shuffled group for every permutation.
        % Means are computed column-wise, ignoring NaN values.
        m1 = mean(shuffled1, 1, 'omitnan');
        m2 = mean(shuffled2, 1, 'omitnan');

        % Calculate and store the modulation indices for the current batch.
        % Element-wise operations evaluate all permutations simultaneously.
        MI_Shuffled(firstPerm:lastPerm) = ...
            (m1 - m2) ./ (m1 + m2);

    end

    % Calculate the percentile rank of the observed modulation index
    % relative to the permutation-based null distribution.
    % compute_percentile assigns half weight to values tied with MI_Real.
    MI_Output(i) = compute_percentile(MI_Shuffled, MI_Real);

end

end

